const PORT: u16 = 41112;
/// Production Relay fleet. Windows parks one responder at each node; Android still keeps exactly
/// one active Relay/session and switches only on natural reconnect/failure events.
const DEFAULT_RELAYS: &str = "conduit-us.414222.xyz:41113;conduit-wa.414222.xyz:41113;conduit-tyo.414222.xyz:41113;conduit-jp.414222.xyz:41113";
/// ponytail: flat retry, no escalation. The desktop is on mains power and the relay is
/// ours, so there is nothing to be polite to; add backoff if it ever rate-limits.
const RELAY_RETRY: Duration = Duration::from_secs(15);
/// Silence this long and we make the peer prove the path is alive. KDE Connect's
/// bug 476747 is the counter-example: OS defaults meant ~7875 s to notice a dead peer.
const IDLE_PING: Duration = Duration::from_secs(60);
/// Over the relay the peer is on cellular or a foreign network, where every ping is a
/// radio wake on a battery. Four an hour instead of sixty, at the cost of noticing a
/// silently dead tunnel later. The phone's read deadline is 2.5x this and follows it.
const RELAY_IDLE_PING: Duration = Duration::from_secs(240);
const PONG_DEADLINE: Duration = Duration::from_secs(10);

/// State for one outstanding liveness challenge.
///
/// An ordinary inbound frame is proof that *one* direction still works, but it is not proof that
/// the peer received our PING. In particular, a half-dead VPN path can keep delivering phone -> PC
/// notification traffic while dropping PC -> phone bytes. Only the PONG generated by our PING may
/// clear this deadline. No timer is added here: the existing blocked receive is simply given the
/// earlier of the normal idle deadline and an already-outstanding PONG deadline.
struct Heartbeat {
    idle: Duration,
    pong_timeout: Duration,
    waiting_until: Option<tokio::time::Instant>,
}

impl Heartbeat {
    fn new(idle: Duration, pong_timeout: Duration) -> Self {
        Self {
            idle,
            pong_timeout,
            waiting_until: None,
        }
    }

    fn deadline(&self, quiet_for: Duration, now: tokio::time::Instant) -> tokio::time::Instant {
        self.waiting_until
            .unwrap_or_else(|| now + self.idle.saturating_sub(quiet_for))
    }

    fn awaiting_pong(&self) -> bool {
        self.waiting_until.is_some()
    }

    fn ping_sent(&mut self, now: tokio::time::Instant) {
        self.waiting_until = Some(now + self.pong_timeout);
    }

    /// Returns true only when this frame satisfies an outstanding liveness challenge.
    fn observe(&mut self, kind: pb::Kind) -> bool {
        if kind == pb::Kind::Pong && self.waiting_until.take().is_some() {
            true
        } else {
            false
        }
    }
}

#[derive(Default)]
struct Metrics {
    created: AtomicU64,
    closed: AtomicU64,
    frames_in: AtomicU64,
    frames_out: AtomicU64,
}

/// Increments `closed` on drop — normal return, error, panic or task abort alike —
/// so `created == closed` after quiesce holds without bookkeeping at every exit.
/// That invariant is the entire reason this project exists.
struct SessionGuard {
    metrics: Arc<Metrics>,
    status: Arc<status::StatusFile>,
}

struct RelayArrival {
    stream: TcpStream,
    endpoint: String,
    pairing: bool,
}

struct CandidateSession {
    stream: TcpStream,
    peer: SocketAddr,
    path: &'static str,
    relay_endpoint: Option<String>,
    generation: u64,
    negotiated: admission::Negotiated,
}

enum ConnectionArrival {
    Socket(TcpStream, SocketAddr, &'static str, Option<String>),
    Authenticated(CandidateSession),
}

impl Drop for SessionGuard {
    fn drop(&mut self) {
        self.status.disconnected();
        let closed = self.metrics.closed.fetch_add(1, Ordering::Relaxed) + 1;
        info!(
            created = self.metrics.created.load(Ordering::Relaxed),
            closed,
            frames_in = self.metrics.frames_in.load(Ordering::Relaxed),
            frames_out = self.metrics.frames_out.load(Ordering::Relaxed),
            "session closed"
        );
    }
}

#[tokio::main(flavor = "multi_thread", worker_threads = 2)]
async fn main() -> Result<()> {
    // Keep the headless daemon, control surface, Start-menu shortcut and toast identity under one
    // Windows application identity. This must happen before any shell/toast interaction.
    unsafe {
        let _ = windows::Win32::UI::Shell::SetCurrentProcessExplicitAppUserModelID(
            &windows::core::HSTRING::from("Conduit.Desktop"),
        );
    }
    tracing_subscriber::fmt()
        .with_env_filter(
            tracing_subscriber::EnvFilter::try_from_default_env()
                .unwrap_or_else(|_| "conduit_daemon=info".into()),
        )
        .init();

    let mut args = std::env::args_os();
    let _exe = args.next();
    if let Some(command) = args.next() {
        if command == "cancel-transfer" {
            let id = args
                .next()
                .context("usage: conduit-daemon cancel-transfer <hex-id>")?;
            if args.next().is_some() {
                bail!("usage: conduit-daemon cancel-transfer <hex-id>");
            }
            control::cancel(&id.to_string_lossy()).await?;
            return Ok(());
        }
        if command == "send" {
            let path = args.next().context("usage: conduit-daemon send <file>")?;
            if args.next().is_some() {
                bail!("usage: conduit-daemon send <file>");
            }
            let mut stdout = std::io::stdout();
            let path = control::queue_with_progress(&PathBuf::from(path), |transferred, total| {
                let _ = writeln!(stdout, "PROGRESS {transferred} {total}");
            })
            .await?;
            // A GUI-subsystem command launched from Explorer may have no stdout handle. Output is
            // best-effort only; publication success belongs to the resident daemon/phone handshake.
            let _ = writeln!(stdout, "Sent to phone: {}", path.display());
            return Ok(());
        }
        if command == "autostart" {
            let action = args
                .next()
                .context("usage: conduit-daemon autostart <install|remove|status>")?;
            if args.next().is_some() {
                bail!("usage: conduit-daemon autostart <install|remove|status>");
            }
            match action.to_string_lossy().as_ref() {
                "install" => println!("Autostart installed: {}", autostart::install()?),
                "remove" => println!(
                    "Autostart {}",
                    if autostart::remove()? {
                        "removed"
                    } else {
                        "was not installed"
                    }
                ),
                "status" => match autostart::status() {
                    Some(value) => println!("Autostart installed: {value}"),
                    None => println!("Autostart not installed"),
                },
                _ => bail!("usage: conduit-daemon autostart <install|remove|status>"),
            }
            return Ok(());
        }
        if command == "explorer" {
            let action = args
                .next()
                .context("usage: conduit-daemon explorer <install|remove|status>")?;
            if args.next().is_some() {
                bail!("usage: conduit-daemon explorer <install|remove|status>");
            }
            match action.to_string_lossy().as_ref() {
                "install" => println!("Explorer integration installed: {}", explorer::install()?),
                "remove" => println!(
                    "Explorer integration {}",
                    if explorer::remove()? {
                        "removed"
                    } else {
                        "was not installed"
                    }
                ),
                "status" => match explorer::status() {
                    Some(value) => println!("Explorer integration installed: {value}"),
                    None => println!("Explorer integration not installed"),
                },
                _ => bail!("usage: conduit-daemon explorer <install|remove|status>"),
            }
            return Ok(());
        }
        if command == "pair" {
            let dir = config_dir()?;
            std::fs::create_dir_all(&dir)?;
            let action = args
                .next()
                .context("usage: conduit-daemon pair <status|start|cancel|forget>")?;
            if args.next().is_some() {
                bail!("usage: conduit-daemon pair <status|start|cancel|forget>");
            }
            match action.to_string_lossy().as_ref() {
                "status" => {
                    let state = pairing::state(&dir);
                    println!("paired={}", state.device_id.is_some());
                    println!("pairing={}", state.pairing);
                    println!("peer_id={}", state.device_id.as_deref().unwrap_or(""));
                    println!("peer_name={}", state.device_name.as_deref().unwrap_or(""));
                    println!(
                        "pairing_code={}",
                        state
                            .pairing_code
                            .as_deref()
                            .map(pairing::format_code)
                            .unwrap_or_default()
                    );
                }
                "start" => {
                    let running = control::pair(control::PairAction::Start).await.is_ok();
                    let window = if running {
                        pairing::state(&dir)
                    } else {
                        let window = pairing::start(&dir)?;
                        pairing::State {
                            pairing: true,
                            pairing_code: Some(window.code),
                            pairing_rendezvous: Some(window.rendezvous),
                            pairing_expires_ms: Some(window.expires_ms),
                            ..Default::default()
                        }
                    };
                    let code = window
                        .pairing_code
                        .as_deref()
                        .map(pairing::format_code)
                        .unwrap_or_else(|| "unavailable".to_string());
                    println!(
                        "Pairing is open for {} seconds. Code: {code}{}",
                        pairing::WINDOW.as_secs(),
                        if running {
                            ""
                        } else {
                            "; it will apply when the daemon starts"
                        }
                    );
                }
                "cancel" => match control::pair(control::PairAction::Cancel).await {
                    Ok(()) => println!("Pairing cancelled."),
                    Err(_) => {
                        pairing::cancel(&dir)?;
                        println!("Pairing cancelled.");
                    }
                },
                "forget" => match control::pair(control::PairAction::Forget).await {
                    Ok(()) => println!("Paired phone forgotten."),
                    Err(_) => {
                        pairing::forget(&dir)?;
                        println!("Paired phone forgotten; no daemon is currently running.");
                    }
                },
                _ => bail!("usage: conduit-daemon pair <status|start|cancel|forget>"),
            }
            return Ok(());
        }
        if command == "reload" && args.next().is_none() {
            control::reload().await?;
            return Ok(());
        }
        if command == "config" {
            let dir = config_dir()?;
            std::fs::create_dir_all(&dir)?;
            let mut config = config::Config::load(&dir)?;
            let action = args.next().context(
                "usage: conduit-daemon config <show|relay-proxy <value|off>|relays <list|off>>",
            )?;
            match action.to_string_lossy().as_ref() {
                "show" if args.next().is_none() => {
                    println!("Config file: {}", dir.join("config.txt").display());
                    println!(
                        "relay_proxy={}",
                        config
                            .relay_proxy
                            .as_deref()
                            .filter(|v| !v.is_empty())
                            .unwrap_or("off")
                    );
                    println!(
                        "relays={}",
                        config.relays.as_deref().unwrap_or(DEFAULT_RELAYS)
                    );
                    if std::env::var_os("CONDUIT_RELAY_PROXY").is_some()
                        || std::env::var_os("CONDUIT_RELAYS").is_some()
                        || std::env::var_os("CONDUIT_RELAY").is_some()
                    {
                        println!(
                            "Note: one or more CONDUIT_* environment variables override this file."
                        );
                    }
                }
                "relay-proxy" => {
                    let value = args
                        .next()
                        .context("usage: conduit-daemon config relay-proxy <value|off>")?;
                    if args.next().is_some() {
                        bail!("usage: conduit-daemon config relay-proxy <value|off>");
                    }
                    let value = value.to_string_lossy();
                    config.relay_proxy = Some(if value.eq_ignore_ascii_case("off") {
                        String::new()
                    } else {
                        value.into_owned()
                    });
                    println!("Saved {}", config.save(&dir)?.display());
                    match control::reload().await {
                        Ok(()) => println!("Applied to the running daemon."),
                        Err(_) => println!("Saved; it will apply when the daemon next starts."),
                    }
                }
                "relays" => {
                    let value = args
                        .next()
                        .context("usage: conduit-daemon config relays <list|off>")?;
                    if args.next().is_some() {
                        bail!("usage: conduit-daemon config relays <list|off>");
                    }
                    let value = value.to_string_lossy();
                    config.relays = Some(if value.eq_ignore_ascii_case("off") {
                        String::new()
                    } else {
                        value.into_owned()
                    });
                    println!("Saved {}", config.save(&dir)?.display());
                    match control::reload().await {
                        Ok(()) => println!("Applied to the running daemon."),
                        Err(_) => println!("Saved; it will apply when the daemon next starts."),
                    }
                }
                _ => bail!(
                    "usage: conduit-daemon config <show|relay-proxy <value|off>|relays <list|off>>"
                ),
            }
            return Ok(());
        }
        if command == "status" && args.next().is_none() {
            let dir = config_dir()?;
            // The daemon itself owns 0.0.0.0:41112. Binding that exact address/port is a
            // side-effect-free, on-demand liveness check; binding only loopback can succeed on
            // Windows even while the wildcard listener exists and would therefore misreport.
            let daemon_running = std::net::TcpListener::bind(("0.0.0.0", PORT)).is_err();
            println!(
                "daemon={}",
                if daemon_running { "running" } else { "stopped" }
            );
            if let Some(snapshot) = status::read(&dir) {
                print!("{snapshot}");
            }
            return Ok(());
        }
        bail!(
            "unknown command {:?}; usage: conduit-daemon [send <file> | status | pair <status|start|cancel|forget> | autostart <install|remove|status> | explorer <install|remove|status> | config ...]",
            command
        );
    }

    let dir = config_dir()?;
    std::fs::create_dir_all(&dir).with_context(|| format!("creating {}", dir.display()))?;
    let user_config = config::Config::load(&dir)?;
    let desktop_status = Arc::new(status::StatusFile::new(&dir)?);
    let identity = wire::load_or_create_identity(&dir.join("identity.bin"))?;
    let device_id = wire::device_id(&identity.public);
    let fingerprint = wire::fingerprint(&identity.public);
    info!(id = %device_id, %fingerprint, "identity");

    // Bind before creating clipboard/toast/control workers. Besides being the LAN listener, this
    // is the process's zero-extra-resource single-instance gate: a manual launch racing the Run
    // entry exits here before it can own any long-lived Conduit resource.
    let listener = TcpListener::bind(("0.0.0.0", PORT))
        .await
        .with_context(|| {
            format!("binding Conduit listener on port {PORT}; is another daemon running?")
        })?;
    info!(port = PORT, "listening");

    // Optional tray icon. It is one blocked Win32 message loop and is not created at all when the
    // setting is off. Failures are non-fatal: transport and clipboard sync remain useful without it.
    let (tray_exit_tx, mut tray_exit_rx) = mpsc::unbounded_channel::<()>();
    let mut tray = if user_config.show_tray_icon() {
        match tray::Tray::start(&dir, tray_exit_tx.clone()) {
            Ok(tray) => {
                info!("tray icon up");
                Some(tray)
            }
            Err(e) => {
                warn!(error = %e, "tray icon unavailable");
                None
            }
        }
    } else {
        info!("tray icon disabled by config");
        None
    };

    let metrics = Arc::new(Metrics::default());
    // One listener thread for the process, started before the socket so a clip copied
    // during the first handshake is already in the ring.
    let bridge = Arc::new(clip::Bridge::start()?);
    // One ephemeral action bus from the already-resident toast thread back into the currently
    // active Noise session. It has no backlog semantics: with no live session receiver, a toast
    // click is dropped rather than replayed against a future/stale Android notification.
    let (toast_action_tx, _) = broadcast::channel::<pb::NotifAction>(16);
    // Likewise one toast thread. A failure here is not fatal: clipboard sync is still
    // worth having on a machine where the notification platform will not cooperate.
    let toasts = match toast::Notifier::start(&dir, toast_action_tx.clone(), bridge.clone()) {
        Ok(notifier) => Some(Arc::new(notifier)),
        Err(e) => {
            warn!(error = %e, "toasts unavailable, mirroring notifications is disabled");
            None
        }
    };
    // One local command queue for the process. File bytes never pass through this IPC; callers
    // name a local path and the resident daemon opens/streams it through its one live session.
    let (outbound_tx, outbound_rx) = mpsc::channel::<control::SendRequest>(16);
    let outbound = Arc::new(Mutex::new(outbound_rx));
    let (reload_tx, mut reload_rx) = mpsc::channel::<control::ReloadRequest>(4);
    let (pair_tx, mut pair_rx) = mpsc::channel::<control::PairRequest>(4);
    let (pair_session_tx, _) = broadcast::channel::<control::PairAction>(4);
    let control_transfers = desktop_status.transfers.clone();
    tokio::spawn(async move {
        if let Err(e) = control::serve(outbound_tx, reload_tx, pair_tx, control_transfers).await {
            warn!(error = %e, "local control pipe stopped");
        }
    });
    // Bound, not dropped: this is what the phone's discovery burst finds. Advertised
    // only once the socket is accepting, so a resolve is never answered by a refusal.
    let _advert = advert::Advert::start(PORT, &device_id, &fingerprint)?;

    // A reconnect can replace a stale session, but a TCP accept cannot. Stage bounded
    // candidate handshakes independently so port probes, invalid peers and slow
    // handshakes never tear down ongoing transfers or the trusted clipboard link.
    //
    // Two ways in now, and the difference ends here: a relay stream is spliced to the
    // phone by a process that cannot read it, so from `serve`'s point of view it is an
    // ordinary socket carrying an ordinary Noise session.
    let mut relay_endpoints = user_config.resolved_relays(DEFAULT_RELAYS);
    let mut relay_proxy = user_config.resolved_proxy();
    info!(
        relays = ?relay_endpoints,
        proxy = relay_proxy.as_deref().unwrap_or("direct"),
        "relay configuration"
    );
    let (mut relay_tasks, mut relay_rx) =
        start_relay_workers(&relay_endpoints, &device_id, relay_proxy.clone());
    let initial_pairing = pairing::state(&dir);
    let (mut pairing_relay_tasks, mut pairing_relay_rx) = match (
        initial_pairing.pairing_rendezvous.as_deref(),
        initial_pairing.pairing_expires_ms,
    ) {
        (Some(rendezvous), Some(expires_ms)) => start_pairing_relay_workers(
            &relay_endpoints,
            rendezvous,
            relay_proxy.clone(),
            expires_ms,
        ),
        _ => empty_relay_workers(),
    };

    let mut active: Option<tokio::task::JoinHandle<()>> = None;
    let mut active_path: Option<&'static str> = None;
    let mut candidates = tokio::task::JoinSet::<Result<CandidateSession>>::new();
    let mut admission_generation = admission::Generation::default();
    loop {
        let arrival = tokio::select! {
            Some(()) = tray_exit_rx.recv() => {
                info!("exit requested from tray");
                break;
            }
            Some(request) = reload_rx.recv() => {
                let result = match config::Config::load(&dir) {
                    Err(e) => Err(format!("{e:#}")),
                    Ok(new_config) => {
                        let wanted_tray = new_config.show_tray_icon();
                        let new_relays = new_config.resolved_relays(DEFAULT_RELAYS);
                        let new_proxy = new_config.resolved_proxy();
                        let relay_changed = new_relays != relay_endpoints || new_proxy != relay_proxy;
                        let mut apply_error = None;

                        if wanted_tray != tray.is_some() {
                            if wanted_tray {
                                match tray::Tray::start(&dir, tray_exit_tx.clone()) {
                                    Ok(new_tray) => {
                                        tray = Some(new_tray);
                                        info!("tray icon enabled without daemon restart");
                                    }
                                    Err(e) => apply_error = Some(format!("starting tray icon: {e:#}")),
                                }
                            } else {
                                tray = None;
                                info!("tray icon disabled without daemon restart");
                            }
                        }

                        if relay_changed {
                            admission_generation.invalidate();
                            candidates.abort_all();
                            for task in relay_tasks.drain(..) {
                                task.abort();
                                let _ = task.await;
                            }
                            let (tasks, rx) =
                                start_relay_workers(&new_relays, &device_id, new_proxy.clone());
                            relay_tasks = tasks;
                            relay_rx = rx;
                            relay_endpoints = new_relays;
                            relay_proxy = new_proxy;
                            for task in pairing_relay_tasks.drain(..) {
                                task.abort();
                                let _ = task.await;
                            }
                            let pair_state = pairing::state(&dir);
                            (pairing_relay_tasks, pairing_relay_rx) = match (
                                pair_state.pairing_rendezvous.as_deref(),
                                pair_state.pairing_expires_ms,
                            ) {
                                (Some(rendezvous), Some(expires_ms)) => start_pairing_relay_workers(
                                    &relay_endpoints,
                                    rendezvous,
                                    relay_proxy.clone(),
                                    expires_ms,
                                ),
                                _ => empty_relay_workers(),
                            };
                            info!(
                                relays = ?relay_endpoints,
                                proxy = relay_proxy.as_deref().unwrap_or("direct"),
                                "relay configuration applied without daemon restart"
                            );
                            // A live relay socket belongs to the old routing configuration. End only
                            // that session so the phone reconnects through the newly parked routes;
                            // a LAN session is left untouched.
                            if active_path.is_some_and(|path| path.starts_with("relay"))
                                && !desktop_status.transfers.has_active() {
                                if let Some(previous) = active.take() {
                                    previous.abort();
                                    let _ = previous.await;
                                }
                                active_path = None;
                            }
                        }

                        match apply_error {
                            Some(message) => Err(message),
                            None => Ok(()),
                        }
                    }
                };
                let _ = request.completion.send(result);
                continue;
            }
            Some(request) = pair_rx.recv() => {
                let result = match request.action {
                    control::PairAction::Start => match pairing::start(&dir) {
                        Ok(window) => {
                            for task in pairing_relay_tasks.drain(..) {
                                task.abort();
                                let _ = task.await;
                            }
                            let (tasks, rx) = start_pairing_relay_workers(
                                &relay_endpoints,
                                &window.rendezvous,
                                relay_proxy.clone(),
                                window.expires_ms,
                            );
                            pairing_relay_tasks = tasks;
                            pairing_relay_rx = rx;
                            info!(code = %pairing::format_code(&window.code), "pairing Relay aliases parked");
                            Ok(())
                        }
                        Err(e) => Err(format!("{e:#}")),
                    },
                    control::PairAction::Cancel => {
                        let result = pairing::cancel(&dir).map(|_| ()).map_err(|e| format!("{e:#}"));
                        if result.is_ok() {
                            for task in pairing_relay_tasks.drain(..) {
                                task.abort();
                                let _ = task.await;
                            }
                            (pairing_relay_tasks, pairing_relay_rx) = empty_relay_workers();
                        }
                        result
                    }
                    control::PairAction::Forget => {
                        let result = pairing::forget(&dir).map(|_| ()).map_err(|e| format!("{e:#}"));
                        if result.is_ok() {
                            for task in pairing_relay_tasks.drain(..) {
                                task.abort();
                                let _ = task.await;
                            }
                            (pairing_relay_tasks, pairing_relay_rx) = empty_relay_workers();
                            let _ = pair_session_tx.send(control::PairAction::Forget);
                            if active.is_none() {
                                desktop_status.disconnected();
                            }
                        }
                        result
                    }
                };
                if result.is_ok() {
                    admission_generation.invalidate();
                    candidates.abort_all();
                }
                let _ = request.completion.send(result);
                continue;
            }
            accepted = listener.accept() => {
                let (stream, peer) = accepted?;
                ConnectionArrival::Socket(stream, peer, "lan", None)
            }
            Some(arrival) = relay_rx.recv() => {
                let Ok(peer) = arrival.stream.peer_addr() else { continue; };
                debug_assert!(!arrival.pairing);
                ConnectionArrival::Socket(arrival.stream, peer, "relay", Some(arrival.endpoint))
            }
            Some(arrival) = pairing_relay_rx.recv() => {
                let Ok(peer) = arrival.stream.peer_addr() else { continue; };
                debug_assert!(arrival.pairing);
                ConnectionArrival::Socket(arrival.stream, peer, "relay-pair", Some(arrival.endpoint))
            }
            Some(completed) = candidates.join_next(), if !candidates.is_empty() => {
                match completed {
                    Ok(Ok(candidate)) => ConnectionArrival::Authenticated(candidate),
                    Ok(Err(error)) => { warn!(%error, "connection candidate refused; live session unchanged"); continue; }
                    Err(error) => { if !error.is_cancelled() { warn!(%error, "candidate task stopped"); } continue; }
                }
            }
        };
        let candidate = match arrival {
            ConnectionArrival::Socket(mut stream, peer, path, relay_endpoint) => {
                if candidates.len() >= admission::MAX_PENDING {
                    warn!(%peer, "connection candidate limit reached; retaining active session");
                    continue;
                }
                let generation = admission_generation.ticket();
                let private_key = identity.private.clone();
                let hello = pb::PairRequest {
                    device_id: device_id.clone(),
                    device_name: advert::hostname(),
                    static_pub: Vec::new(),
                    version: env!("CARGO_PKG_VERSION").to_string(),
                    wallpaper_hash: wallpaper::cached_hash(&dir),
                    pairing: pairing::state(&dir).pairing,
                    transfer_protocol: 1,
                };
                candidates.spawn(async move {
                    stream.set_nodelay(true)?;
                    set_keepalive(&stream)?;
                    let negotiated = tokio::time::timeout(
                        admission::TIMEOUT,
                        admission::negotiate(&mut stream, &private_key, &hello),
                    )
                    .await
                    .context("candidate authentication timed out")??;
                    Ok(CandidateSession {
                        stream,
                        peer,
                        path,
                        relay_endpoint,
                        generation,
                        negotiated,
                    })
                });
                continue;
            }
            ConnectionArrival::Authenticated(candidate) => candidate,
        };
        if !admission_generation.accepts(candidate.generation) {
            continue;
        }
        // Pair/Forget and another admitted connection may have changed policy while
        // this candidate was doing I/O. Only the main loop may persist a new peer.
        let authorization = match pairing::authorize(
            &dir,
            &candidate.negotiated.remote_id,
            candidate.path,
            candidate.negotiated.hello.pairing,
        ) {
            Ok(authorization) => authorization,
            Err(error) => {
                warn!(%error, "candidate is not paired; retaining active session");
                continue;
            }
        };
        if authorization == pairing::Authorization::Trusted
            && candidate.path == "lan"
            && active_path.is_some_and(|path| path.starts_with("relay"))
            && desktop_status.transfers.has_active()
        {
            info!("deferring optional LAN promotion while transfers are active");
            continue;
        }
        if let Err(error) = pairing::confirm(
            &dir,
            &candidate.negotiated.remote_id,
            authorization,
            &candidate.negotiated.hello.device_name,
        ) {
            warn!(%error, "could not commit candidate trust; retaining active session");
            continue;
        }
        admission_generation.invalidate();
        candidates.abort_all();
        let CandidateSession {
            stream,
            peer,
            path: via,
            relay_endpoint,
            negotiated,
            ..
        } = candidate;
        info!(%peer, via, relay = relay_endpoint.as_deref().unwrap_or("-"), "authenticated peer promoted");
        if let Some(previous) = active.take() {
            previous.abort();
            let _ = previous.await; // guard drop runs here — closed is counted
        }
        let created = metrics.created.fetch_add(1, Ordering::Relaxed) + 1;
        info!(
            created,
            closed = metrics.closed.load(Ordering::Relaxed),
            "session created"
        );
        let metrics = metrics.clone();
        let bridge = bridge.clone();
        let toasts = toasts.clone();
        let outbound = outbound.clone();
        let relay_endpoint = relay_endpoint.clone();
        let desktop_status = desktop_status.clone();
        let toast_action_tx = toast_action_tx.clone();
        let pair_session_tx = pair_session_tx.clone();
        let data_dir = dir.clone();
        active_path = Some(via);
        active = Some(tokio::spawn(async move {
            let _guard = SessionGuard {
                metrics: metrics.clone(),
                status: desktop_status.clone(),
            };
            if let Err(e) = serve(
                stream,
                peer,
                negotiated,
                &metrics,
                &bridge,
                &outbound,
                toasts.as_ref(),
                via,
                relay_endpoint.as_deref(),
                &desktop_status,
                &toast_action_tx,
                &pair_session_tx,
                &data_dir,
            )
            .await
            {
                warn!(%peer, error = %e, "session ended");
            }
        }));
    }

    candidates.abort_all();
    if let Some(session) = active.take() {
        session.abort();
        let _ = session.await;
    }
    for task in pairing_relay_tasks.drain(..) {
        task.abort();
        let _ = task.await;
    }
    desktop_status.disconnected();
    Ok(())
}

fn start_relay_workers(
    relays: &[String],
    rendezvous: &str,
    relay_proxy: Option<String>,
) -> (
    Vec<tokio::task::JoinHandle<()>>,
    tokio::sync::mpsc::Receiver<RelayArrival>,
) {
    let (relay_tx, relay_rx) =
        tokio::sync::mpsc::channel::<RelayArrival>((relays.len().max(1) * 2).max(2));
    let mut tasks = Vec::with_capacity(relays.len());
    for endpoint in relays {
        info!(%endpoint, "parking at relay");
        tasks.push(tokio::spawn(park_forever(
            endpoint.clone(),
            rendezvous.to_owned(),
            relay_tx.clone(),
            relay_proxy.clone(),
            false,
        )));
    }
    // Only workers own senders. With no configured relays this closes the receiver and makes the
    // `Some(arrival)` select branch dormant without any poll or special timer.
    drop(relay_tx);
    (tasks, relay_rx)
}

fn empty_relay_workers() -> (
    Vec<tokio::task::JoinHandle<()>>,
    tokio::sync::mpsc::Receiver<RelayArrival>,
) {
    let (tx, rx) = tokio::sync::mpsc::channel(1);
    drop(tx);
    (Vec::new(), rx)
}

fn start_pairing_relay_workers(
    relays: &[String],
    rendezvous: &str,
    relay_proxy: Option<String>,
    expires_ms: u128,
) -> (
    Vec<tokio::task::JoinHandle<()>>,
    tokio::sync::mpsc::Receiver<RelayArrival>,
) {
    let (relay_tx, relay_rx) =
        tokio::sync::mpsc::channel::<RelayArrival>((relays.len().max(1) * 2).max(2));
    let now_ms = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_millis();
    let remaining_ms = expires_ms.saturating_sub(now_ms).min(u64::MAX as u128) as u64;
    if remaining_ms == 0 {
        drop(relay_tx);
        return (Vec::new(), relay_rx);
    }
    let deadline = tokio::time::Instant::now() + Duration::from_millis(remaining_ms);
    let mut tasks = Vec::with_capacity(relays.len());
    for endpoint in relays {
        info!(%endpoint, "parking temporary pairing alias at relay");
        tasks.push(tokio::spawn(park_until(
            endpoint.clone(),
            rendezvous.to_owned(),
            relay_tx.clone(),
            relay_proxy.clone(),
            deadline,
        )));
    }
    drop(relay_tx);
    (tasks, relay_rx)
}

async fn park_until(
    endpoint: String,
    rendezvous: String,
    tx: tokio::sync::mpsc::Sender<RelayArrival>,
    relay_proxy: Option<String>,
    deadline: tokio::time::Instant,
) {
    loop {
        let remaining = deadline.saturating_duration_since(tokio::time::Instant::now());
        if remaining.is_zero() {
            return;
        }
        match tokio::time::timeout(
            remaining,
            wire::park(&endpoint, &rendezvous, relay_proxy.as_deref()),
        )
        .await
        {
            Ok(Ok(stream)) => {
                if let Err(e) = set_keepalive(&stream) {
                    warn!(error = %e, "pairing relay stream without keepalive");
                }
                if tx
                    .send(RelayArrival {
                        stream,
                        endpoint: endpoint.clone(),
                        pairing: true,
                    })
                    .await
                    .is_err()
                {
                    return;
                }
            }
            Ok(Err(e)) => {
                warn!(%endpoint, error = %e, "pairing relay unreachable");
                let nap = RELAY_RETRY
                    .min(deadline.saturating_duration_since(tokio::time::Instant::now()));
                if nap.is_zero() {
                    return;
                }
                tokio::time::sleep(nap).await;
            }
            Err(_) => return,
        }
    }
}

/// Keeps exactly one connection parked at the relay for the life of the process.
///
/// Re-parks immediately after handing a stream over, so a reconnecting phone always
/// finds a partner already waiting instead of racing the desktop to the rendezvous.
/// The relay pairs whoever presents the id, so a stale park is harmless: the next
/// arrival is spliced to the newest one.
async fn park_forever(
    endpoint: String,
    rendezvous: String,
    tx: tokio::sync::mpsc::Sender<RelayArrival>,
    relay_proxy: Option<String>,
    pairing: bool,
) {
    loop {
        match wire::park(&endpoint, &rendezvous, relay_proxy.as_deref()).await {
            Ok(stream) => {
                if let Err(e) = set_keepalive(&stream) {
                    warn!(error = %e, "relay stream without keepalive");
                }
                // Closed channel means main returned; nothing left to serve.
                if tx
                    .send(RelayArrival {
                        stream,
                        endpoint: endpoint.clone(),
                        pairing,
                    })
                    .await
                    .is_err()
                {
                    return;
                }
            }
            Err(e) => {
                warn!(%endpoint, error = %e, "relay unreachable");
                tokio::time::sleep(RELAY_RETRY).await;
            }
        }
    }
}

async fn serve(
    stream: TcpStream,
    peer: SocketAddr,
    negotiated: admission::Negotiated,
    metrics: &Metrics,
    bridge: &Arc<clip::Bridge>,
    outbound: &Arc<Mutex<mpsc::Receiver<control::SendRequest>>>,
    toasts: Option<&Arc<toast::Notifier>>,
    // "lan" or "relay". Only the keepalive interval and the log line care.
    path: &'static str,
    relay_endpoint: Option<&str>,
    desktop_status: &status::StatusFile,
    toast_action_tx: &broadcast::Sender<pb::NotifAction>,
    pair_session_tx: &broadcast::Sender<control::PairAction>,
    data_dir: &std::path::Path,
) -> Result<()> {
    let idle_ping = if path.starts_with("relay") {
        RELAY_IDLE_PING
    } else {
        IDLE_PING
    };

    let admission::Negotiated {
        mut session,
        remote_id,
        hello: peer_hello,
    } = negotiated;
    metrics.frames_out.fetch_add(1, Ordering::Relaxed);
    metrics.frames_in.fetch_add(1, Ordering::Relaxed);
    desktop_status.linked(
        &remote_id,
        if path.starts_with("relay") {
            "relay"
        } else {
            path
        },
        relay_endpoint,
    );
    desktop_status.peer_name(&peer_hello.device_name);
    info!(
        name = %peer_hello.device_name,
        version = %peer_hello.version,
        id = %remote_id,
        "peer pairing confirmed"
    );

    // Subscribed after the pairing handshake so the session does not replay clips copied
    // while it was still connecting.
    let mut clips = bridge.subscribe();
    // Same semantics for user-initiated toast actions: only the live authenticated session may
    // consume them, and broadcast deliberately has no durable queue across reconnects.
    let mut toast_actions = toast_action_tx.subscribe();
    let mut pair_actions = pair_session_tx.subscribe();
    // At most one image in flight, and it dies with the session: a peer that vanishes
    // mid-transfer cannot leave a partial buffer behind for the next one to inherit.
    let mut incoming: Option<image::Assembly> = None;
    // Same rule for a file, with teeth: `Incoming`'s Drop deletes the partial, so a
    // session ending mid-transfer cannot leave scratch files in Downloads.
    let mut arriving: Option<transfer::Receiving> = None;
    // One desktop->phone file may be awaiting its receiver-side publication result. Other local
    // requests stay in the bounded control queue until this completes, so results cannot cross.
    let mut sending: Option<transfer::Sending> = None;
    let mut queued = std::collections::VecDeque::<control::SendRequest>::new();
    let capable = peer_hello.transfer_protocol >= 1;
    let lease = desktop_status.transfers.session(capable)?;
    let transfers = &lease.transfers;
    let owner = &lease.owner;
    let (received_tx, mut received_rx) = mpsc::channel::<transfer::Received>(4);
    let mut outgoing_image: Option<image::Outgoing> = None;
    let mut next_image: Option<image::Outgoing> = None;
    let image_jobs = image::processor(bridge.clone(), toasts.cloned());
    let mut file_turn = true;
    let mut heartbeat = Heartbeat::new(idle_ping, PONG_DEADLINE);
    let (mut reader, socket_writer) = stream.into_split();
    let mut stream = transfer::Writer::start(socket_writer);

    loop {
        // A request belongs to the authenticated session that accepted it, never its replacement.
        let mut index = 0;
        while index < queued.len() {
            if queued[index].owner != *owner || transfers.cancelled(owner, &queued[index].id) {
                let mut request = queued.remove(index).unwrap();
                let cancelled = request.owner == *owner;
                transfers.update(
                    &request.owner,
                    &request.id,
                    0,
                    if cancelled { "cancelled" } else { "failed" },
                    "Transfer no longer queued",
                );
                request.finish(Err(if cancelled {
                    "Cancelled"
                } else {
                    "Session changed"
                }
                .into()));
            } else {
                index += 1;
            }
        }
        if sending.is_none() {
            if let Some(request) = queued.pop_front() {
                sending = Some(transfer::Sending::start(request));
            }
        }
        if arriving
            .as_ref()
            .is_some_and(|rx| transfers.cancelled(owner, &rx.id) && !rx.cancel_sent)
            && stream.control_ready()
        {
            if let Some(rx) = &mut arriving {
                let cancel = pb::FileCancel {
                    transfer_id: rx.id.clone(),
                    reason: "Cancelled by receiver".into(),
                };
                session
                    .send(&mut stream, pb::Kind::FileCancel, &cancel.encode_to_vec())
                    .await?;
                metrics.frames_out.fetch_add(1, Ordering::Relaxed);
                rx.cancel();
                rx.cancel_sent = true;
            }
        }
        if sending.as_ref().is_some_and(|s| {
            transfers.cancelled(owner, &s.request.id) && !s.cancel_sent && s.total > 0
        }) && stream.control_ready()
        {
            let active = sending.as_mut().unwrap();
            if capable {
                let cancel = pb::FileCancel {
                    transfer_id: active.request.id.clone(),
                    reason: "Cancelled by sender".into(),
                };
                session
                    .send(&mut stream, pb::Kind::FileCancel, &cancel.encode_to_vec())
                    .await?;
                metrics.frames_out.fetch_add(1, Ordering::Relaxed);
            }
            active.stop_producer();
            active.cancel_sent = true;
            active.waiting = Some(tokio::time::Instant::now() + transfer::RESULT_TIMEOUT);
            transfers.update(
                owner,
                &active.request.id,
                active.sent,
                "waiting confirmation",
                "Cancellation requested",
            );
        }
        if sending.as_ref().is_some_and(|s| {
            (transfers.cancelled(owner, &s.request.id) && s.total == 0)
                || s.expired(tokio::time::Instant::now())
        }) {
            let mut active = sending.take().unwrap();
            let cancelled = transfers.cancelled(owner, &active.request.id);
            let reason = if cancelled {
                "Cancelled"
            } else {
                "Timed out waiting for receiver publication"
            };
            if capable && active.total > 0 && !active.cancel_sent && stream.control_ready() {
                let cancel = pb::FileCancel {
                    transfer_id: active.request.id.clone(),
                    reason: reason.into(),
                };
                session
                    .send(&mut stream, pb::Kind::FileCancel, &cancel.encode_to_vec())
                    .await?;
                metrics.frames_out.fetch_add(1, Ordering::Relaxed);
            }
            transfers.update(
                owner,
                &active.request.id,
                active.sent,
                if cancelled { "cancelled" } else { "failed" },
                reason,
            );
            active.request.finish(Err(reason.into()));
            if let Some(toasts) = toasts {
                toasts.post(toast::Cmd::TransferResult {
                    name: active
                        .request
                        .path
                        .file_name()
                        .unwrap_or_default()
                        .to_string_lossy()
                        .into_owned(),
                    success: false,
                });
            }
        }
        // Time left before this side owes the peer a frame. Measured from our last
        // *send*, not from the last thing we heard: the phone's read deadline can only
        // be satisfied by us speaking, so a phone that chats steadily while hearing
        // nothing back used to tear down a perfectly healthy session on the dot. It
        // also still catches a dead peer, because a ping demands a pong.
        let deadline = heartbeat.deadline(session.quiet_for(), tokio::time::Instant::now());
        let result_deadline = sending.as_ref().and_then(|s| s.waiting);
        let data_ready = stream.data_ready();
        let control_ready = stream.control_ready();
        let writer_slots = stream.slots();
        // `recv` is cancel-safe, which is what makes racing it legal. `send` is not,
        // but a `select!` branch body runs to completion once chosen, so the sends
        // below are never cancelled mid-frame. While a PONG is outstanding, local outbound
        // work pauses for at most ten seconds so it cannot hide the liveness deadline.
        let envelope = tokio::select! {
            result = session.recv(&mut reader), if arriving.as_ref().is_none_or(|r| r.tx.capacity() > 0) && image_jobs.capacity() > 0 && control_ready => result?,
            _ = tokio::time::sleep_until(deadline) => {
                if heartbeat.awaiting_pong() { bail!("peer silent past pong deadline"); }
                if !control_ready { bail!("socket writer stalled past heartbeat deadline"); }
                    session.send(&mut stream, pb::Kind::Ping, &[]).await?;
                    metrics.frames_out.fetch_add(1, Ordering::Relaxed);
                    heartbeat.ping_sent(tokio::time::Instant::now());
                    continue;
            },
            local = clips.recv(), if !heartbeat.awaiting_pong() && data_ready => {
                match local {
                    Ok(clip::Clip::Text(text)) => {
                        let clip = pb::ClipText {
                            timestamp_ms: now_ms(),
                            mime: "text/plain".into(),
                            text,
                        };
                        let payload = clip.encode_to_vec();
                        if payload.len() > wire::MAX_PLAINTEXT - 32 {
                            warn!(bytes = payload.len(), "oversized local clipboard text refused; transfers unchanged");
                            continue;
                        }
                        session
                            .send(&mut stream, pb::Kind::ClipText, &payload)
                            .await?;
                        metrics.frames_out.fetch_add(1, Ordering::Relaxed);
                    }
                    Ok(clip::Clip::Image(png)) => {
                        info!(bytes = png.len(), "clip image out");
                        // Keep the latest clipboard value behind an image already being sent.
                        match image::Outgoing::new(png) {
                            Ok(image) if outgoing_image.is_none() => outgoing_image = Some(image),
                            Ok(image) => next_image = Some(image),
                            Err(e) => warn!(error = %e, "local clipboard image refused"),
                        }
                    }
                    // The ring overwrote clips faster than this session drained them.
                    // Skipping is correct: only the newest clipboard state matters.
                    Err(broadcast::error::RecvError::Lagged(n)) => {
                        warn!(skipped = n, "clip ring lagged")
                    }
                    Err(broadcast::error::RecvError::Closed) => {
                        anyhow::bail!("clipboard bridge is gone")
                    }
                }
                continue;
            }
            local_file = async {
                let mut rx = outbound.lock().await;
                rx.recv().await
            }, if queued.len() < 16 => {
                let Some(request) = local_file else {
                    bail!("local outbound file queue closed")
                };
                queued.push_back(request);
                continue;
            }
            _ = transfers.wake.notified() => { continue; }
            result = &mut stream.task => { bail!("session writer stopped: {result:?}"); }
            _ = async { if let Ok(permit) = writer_slots.reserve_many(4).await { drop(permit); } }, if !data_ready => { continue; }
            _ = async { let r = arriving.as_ref().unwrap(); let _ = r.tx.reserve().await; },
                if arriving.as_ref().is_some_and(|r| r.tx.capacity() == 0) => { continue; }
            _ = async { tokio::time::sleep_until(result_deadline.unwrap()).await; },
                if result_deadline.is_some() => { continue; }
            _ = async { let _ = image_jobs.reserve().await; }, if image_jobs.capacity() == 0 => { continue; }
            Some(received) = received_rx.recv(), if control_ready => {
                if arriving.as_ref().is_none_or(|r| r.id != received.result.transfer_id) { continue; }
                arriving = None;
                session.send(&mut stream, pb::Kind::FileResult, &received.result.encode_to_vec()).await?;
                metrics.frames_out.fetch_add(1, Ordering::Relaxed);
                if let Some(path) = received.path {
                    if let Some(toasts) = toasts { toasts.post(toast::Cmd::File { path }); }
                }
                continue;
            }
            frame = async { sending.as_mut().unwrap().frames.recv().await },
                if sending.as_ref().is_some_and(|s| s.waiting.is_none()) && !heartbeat.awaiting_pong() && data_ready
                    && (file_turn || outgoing_image.is_none()) => {
                file_turn = false;
                let active = sending.as_mut().unwrap();
                match frame {
                    Some(Ok(frame)) => {
                        if frame.kind == pb::Kind::FileOffer && !transfers.claim(owner, &active.request.id, frame.total) {
                            transfers.update(owner, &active.request.id, 0, "cancelled", "Cancelled before offering");
                            active.request.finish(Err("Cancelled before offering".into()));
                            sending = None;
                            continue;
                        }
                        // This complete frame write is outside every select/timeout.
                        session.send(&mut stream, frame.kind, &frame.payload).await?;
                        metrics.frames_out.fetch_add(1, Ordering::Relaxed);
                        active.sent = frame.bytes; active.total = frame.total;
                        let waiting = frame.kind == pb::Kind::FileChunk && frame.bytes == frame.total;
                        if waiting { active.waiting = Some(tokio::time::Instant::now() + transfer::RESULT_TIMEOUT); }
                        transfers.update(owner, &active.request.id, frame.bytes, if waiting { "waiting confirmation" } else { "transferring" }, "");
                        let name = active.request.path.file_name().unwrap_or_default().to_string_lossy().into_owned();
                        if frame.kind == pb::Kind::FileOffer || waiting || active.last_progress.elapsed() >= Duration::from_millis(250) {
                            active.last_progress = std::time::Instant::now();
                            active.request.progress.send_replace(control::TransferProgress { transferred: frame.bytes, total: frame.total });
                            if let Some(toasts) = toasts {
                                if frame.kind == pb::Kind::FileOffer { toasts.post(toast::Cmd::TransferStart { name, total: frame.total }); }
                                else { toasts.post(toast::Cmd::TransferProgress { name, transferred: frame.bytes, total: frame.total, waiting_for_phone: waiting }); }
                            }
                        }
                    }
                    other => {
                        let reason = match other { Some(Err(e)) => format!("{e:#}"), _ => "File producer stopped".into() };
                        if capable {
                            let cancel = pb::FileCancel { transfer_id: active.request.id.clone(), reason: reason.clone() };
                            session.send(&mut stream, pb::Kind::FileCancel, &cancel.encode_to_vec()).await?;
                            metrics.frames_out.fetch_add(1, Ordering::Relaxed);
                        }
                        transfers.update(owner, &active.request.id, active.sent, "failed", &reason);
                        active.request.finish(Err(reason));
                        sending = None;
                    }
                }
                continue;
            }
            _ = std::future::ready(()), if outgoing_image.is_some() && !heartbeat.awaiting_pong() && data_ready
                && (!file_turn || sending.as_ref().is_none_or(|s| s.waiting.is_some() || s.frames.is_empty())) => {
                file_turn = true;
                let image = outgoing_image.as_mut().unwrap();
                if let Some((kind, payload)) = image.next_frame() {
                    session.send(&mut stream, kind, &payload).await?;
                    metrics.frames_out.fetch_add(1, Ordering::Relaxed);
                } else { outgoing_image = next_image.take(); }
                continue;
            }
            action = toast_actions.recv(), if !heartbeat.awaiting_pong() && control_ready => {
                match action {
                    Ok(action) => {
                        session
                            .send(&mut stream, pb::Kind::NotifAction, &action.encode_to_vec())
                            .await?;
                        metrics.frames_out.fetch_add(1, Ordering::Relaxed);
                    }
                    Err(broadcast::error::RecvError::Lagged(n)) => {
                        // User clicks are rare. If something ever floods this bounded channel,
                        // dropping old actions is safer than executing stale capabilities later.
                        warn!(skipped = n, "toast action ring lagged");
                    }
                    Err(broadcast::error::RecvError::Closed) => {
                        warn!("toast action channel closed");
                    }
                }
                continue;
            }
            action = pair_actions.recv(), if !heartbeat.awaiting_pong() && control_ready => {
                match action {
                    Ok(control::PairAction::Forget) => {
                        let response = pb::PairResponse { accept: false, static_pub: Vec::new() };
                        session
                            .send(&mut stream, pb::Kind::PairResponse, &response.encode_to_vec())
                            .await?;
                        let _ = tokio::time::timeout(Duration::from_secs(2), stream.drain()).await;
                        metrics.frames_out.fetch_add(1, Ordering::Relaxed);
                        bail!("local user forgot the paired phone");
                    }
                    Ok(_) => {}
                    Err(broadcast::error::RecvError::Lagged(_)) => {
                        if pairing::peer_id(data_dir).is_none() {
                            bail!("paired phone was forgotten");
                        }
                    }
                    Err(broadcast::error::RecvError::Closed) => {}
                }
                continue;
            }
        };
        metrics.frames_in.fetch_add(1, Ordering::Relaxed);
        heartbeat.observe(envelope.kind());

        match envelope.kind() {
            pb::Kind::Ping => {
                session.send(&mut stream, pb::Kind::Pong, &[]).await?;
                metrics.frames_out.fetch_add(1, Ordering::Relaxed);
            }
            pb::Kind::Pong => {}
            pb::Kind::ClipText => {
                let Ok(clip) = pb::ClipText::decode(&envelope.payload[..]) else {
                    warn!("malformed clipboard text dropped");
                    continue;
                };
                info!(bytes = clip.text.len(), mime = %clip.mime, "clip text in");
                // A clipboard failure is the peer's problem, not the session's.
                if let Err(e) = image_jobs.try_send(image::IncomingWork::Text(clip.text)) {
                    warn!(error = %e, "could not set the clipboard");
                }
            }
            // A bad image is dropped, never fatal — same rule as a bad notification.
            // The peer controls every field here, so a refused header must cost this
            // side an allocation of zero and the session nothing at all.
            pb::Kind::ClipImageHeader => {
                let Ok(header) = pb::ClipImageHeader::decode(&envelope.payload[..]) else {
                    warn!("malformed image header dropped");
                    continue;
                };
                if incoming.is_some() {
                    warn!("second image header refused while receiving");
                    continue;
                }
                match image::Assembly::begin(&header) {
                    Ok(assembly) => {
                        info!(
                            bytes = header.total_bytes,
                            chunks = header.chunk_count,
                            mime = %header.mime,
                            photo = header.photo,
                            screenshot = header.screenshot,
                            "image in, receiving"
                        );
                        incoming = Some(assembly);
                    }
                    Err(e) => {
                        warn!(error = %e, "refused an image header");
                        incoming = None;
                    }
                }
            }
            pb::Kind::ClipImageChunk => {
                let Ok(chunk) = pb::ClipImageChunk::decode(&envelope.payload[..]) else {
                    warn!("malformed image chunk dropped");
                    continue;
                };
                let Some(assembly) = incoming.as_mut() else {
                    warn!(index = chunk.index, "image chunk with no header, dropped");
                    continue;
                };
                if !assembly.matches(&chunk.header_id) {
                    continue;
                }
                match assembly.push(&chunk) {
                    Ok(None) => {}
                    Ok(Some(png)) => {
                        let photo = assembly.is_photo();
                        let screenshot = assembly.is_screenshot();
                        incoming = None;
                        info!(bytes = png.len(), photo, screenshot, "image complete");
                        if let Err(e) = image_jobs.try_send(image::IncomingWork::Image {
                            bytes: png,
                            photo,
                            screenshot,
                        }) {
                            warn!(error = %e, "image processing queue closed");
                        }
                    }
                    Err(e) => {
                        warn!(error = %e, "image transfer dropped");
                        incoming = None;
                    }
                }
            }
            pb::Kind::WallpaperPreview => {
                match pb::WallpaperPreview::decode(&envelope.payload[..]) {
                    Ok(preview) => match wallpaper::store(data_dir, &preview) {
                        Ok(true) => info!(
                            bytes = preview.jpeg.len(),
                            "phone wallpaper preview updated"
                        ),
                        Ok(false) => {}
                        Err(e) => warn!(error = %e, "refused phone wallpaper preview"),
                    },
                    Err(e) => warn!(error = %e, "malformed phone wallpaper preview dropped"),
                }
            }
            pb::Kind::SharedUrl => {
                let Ok(shared) = pb::SharedUrl::decode(&envelope.payload[..]) else {
                    warn!("malformed shared URL dropped");
                    continue;
                };
                let scheme = shared.url.to_ascii_lowercase();
                if !scheme.starts_with("http://") && !scheme.starts_with("https://") {
                    warn!(url = %shared.url, "refused non-web shared URL");
                    continue;
                }
                info!(url = %shared.url, source = %shared.source_device, "shared URL in");
                if let Err(e) = shared_links::record(
                    data_dir,
                    &shared.url,
                    &shared.title,
                    &shared.source_device,
                    shared.timestamp_ms,
                ) {
                    // History is convenience UI, never a reason to break the transport session.
                    warn!(error = %e, "could not record shared URL history");
                }
                if let Some(toasts) = toasts {
                    toasts.post(toast::Cmd::SharedUrl {
                        url: shared.url,
                        title: shared.title,
                        source: shared.source_device,
                    });
                }
            }
            // A malformed notification is dropped, never fatal: the phone's shade must
            // not be able to end a session that is also carrying the clipboard.
            pb::Kind::NotifNew => {
                let Ok(notif) = pb::NotifNew::decode(&envelope.payload[..]) else {
                    warn!("malformed notification dropped");
                    continue;
                };
                info!(app = %notif.app_name, pkg = %notif.package, messages = notif.messages.len(), "notif in");
                let app = if notif.app_name.is_empty() {
                    notif.package.clone()
                } else {
                    notif.app_name.clone()
                };
                if let Err(e) = notification_history::record_new(
                    data_dir,
                    &notif.key,
                    &notif.package,
                    &app,
                    &notif.title,
                    &notif.text,
                    notif.timestamp_ms,
                ) {
                    warn!(error = %e, "could not record notification history");
                }
                if let Some(toasts) = toasts {
                    toasts.post(toast::Cmd::Show {
                        key: notif.key,
                        package: notif.package,
                        app,
                        title: notif.title,
                        body: notif.text,
                        messages: notif.messages,
                        app_icon: notif.app_icon_png,
                        avatar: notif.large_icon_png,
                        actions: notif.actions,
                        suppress_popup: notif.suppress_popup,
                    });
                }
            }
            pb::Kind::NotifUpdate => {
                let Ok(notif) = pb::NotifUpdate::decode(&envelope.payload[..]) else {
                    warn!("malformed notification update dropped");
                    continue;
                };
                if let Err(e) = notification_history::record_update(
                    data_dir,
                    &notif.key,
                    &notif.title,
                    &notif.text,
                ) {
                    warn!(error = %e, "could not update notification history");
                }
                if let Some(toasts) = toasts {
                    toasts.post(toast::Cmd::Update {
                        key: notif.key,
                        title: notif.title,
                        body: notif.text,
                        messages: notif.messages,
                    });
                }
            }
            pb::Kind::NotifRemove => {
                let Ok(notif) = pb::NotifRemove::decode(&envelope.payload[..]) else {
                    warn!("malformed notification removal dropped");
                    continue;
                };
                if let Some(toasts) = toasts {
                    toasts.post(toast::Cmd::Hide { key: notif.key });
                }
            }
            // The phone announcing itself. Nothing to do with it on this side yet — the
            // desktop already knows which peer it is talking to — but decoding it keeps it
            // out of the "unhandled kind" log.
            pb::Kind::PairRequest => {
                let Ok(hello) = pb::PairRequest::decode(&envelope.payload[..]) else {
                    warn!("malformed peer hello dropped");
                    continue;
                };
                if !hello.device_id.is_empty() && hello.device_id != remote_id {
                    bail!("peer announced an id that does not match its Noise static key");
                }
                info!(name = %hello.device_name, version = %hello.version, "peer named itself");
                desktop_status.peer_name(&hello.device_name);
                if let Err(e) = pairing::remember_name(data_dir, &hello.device_name) {
                    warn!(error = %e, "could not persist paired phone name");
                }
            }
            pb::Kind::PairResponse => {
                let Ok(response) = pb::PairResponse::decode(&envelope.payload[..]) else {
                    warn!("malformed pairing response dropped");
                    continue;
                };
                if !response.accept {
                    pairing::forget(data_dir)?;
                    bail!("paired phone removed this desktop");
                }
            }
            // A file, same leniency as an image: a refused offer costs the transfer and
            // nothing else. The session is also carrying the clipboard, and a phone that
            // shares a 600 MB video must not knock it out.
            pb::Kind::FileOffer => {
                let Ok(offer) = pb::FileOffer::decode(&envelope.payload[..]) else {
                    warn!("malformed file offer dropped");
                    continue;
                };
                if offer.transfer_id.is_empty() || offer.transfer_id.len() > 64 {
                    warn!("invalid file id dropped");
                    continue;
                }
                // A duplicate active offer must not send a negative result for that same ID.
                if arriving
                    .as_ref()
                    .is_some_and(|rx| rx.id == offer.transfer_id)
                {
                    continue;
                }
                let refusal = if arriving.is_some() {
                    if transfers.incoming(owner, &offer).is_ok() {
                        transfers.update(
                            owner,
                            &offer.transfer_id,
                            0,
                            "failed",
                            "Receiver is busy",
                        );
                    }
                    Some("Receiver is busy".to_string())
                } else {
                    transfers
                        .incoming(owner, &offer)
                        .err()
                        .map(|e| e.to_string())
                };
                if let Some(error) = refusal {
                    let result = pb::FileResult {
                        transfer_id: offer.transfer_id,
                        success: false,
                        error,
                        name: offer.name.chars().take(256).collect(),
                        cancelled: false,
                    };
                    session
                        .send(&mut stream, pb::Kind::FileResult, &result.encode_to_vec())
                        .await?;
                    metrics.frames_out.fetch_add(1, Ordering::Relaxed);
                } else {
                    arriving = Some(transfer::Receiving::start(
                        offer,
                        data_dir.to_path_buf(),
                        owner.clone(),
                        transfers.clone(),
                        received_tx.clone(),
                    ));
                }
            }
            pb::Kind::FileChunk => {
                let Ok(chunk) = pb::FileChunk::decode(&envelope.payload[..]) else {
                    warn!("malformed file chunk dropped");
                    continue;
                };
                if let Some(rx) = &arriving {
                    // Wrong/late IDs are isolated before they can touch the active file.
                    if chunk.transfer_id == rx.id {
                        if let Err(e) = rx.tx.try_send(chunk) {
                            warn!(error = %e, "receive worker closed");
                        }
                    }
                }
            }
            pb::Kind::FileResult => {
                let Ok(result) = pb::FileResult::decode(&envelope.payload[..]) else {
                    warn!("malformed file result dropped");
                    continue;
                };
                if sending.as_ref().is_none_or(|s| !s.accepts(&result)) {
                    continue;
                }
                let mut active = sending.take().unwrap();
                let state = if result.success {
                    "completed"
                } else if result.cancelled {
                    "cancelled"
                } else {
                    "failed"
                };
                let reason: String = if result.error.is_empty() {
                    if result.cancelled {
                        "Cancelled".into()
                    } else {
                        "Receiver refused the file".into()
                    }
                } else {
                    result.error.chars().take(512).collect()
                };
                transfers.update(
                    owner,
                    &active.request.id,
                    active.sent,
                    state,
                    if result.success { "" } else { &reason },
                );
                if let Some(toasts) = toasts {
                    toasts.post(toast::Cmd::TransferResult {
                        name: active
                            .request
                            .path
                            .file_name()
                            .unwrap_or_default()
                            .to_string_lossy()
                            .into_owned(),
                        success: result.success,
                    });
                }
                active
                    .request
                    .finish(if result.success { Ok(()) } else { Err(reason) });
            }
            pb::Kind::FileCancel => {
                let Ok(cancel) = pb::FileCancel::decode(&envelope.payload[..]) else {
                    warn!("malformed cancellation dropped");
                    continue;
                };
                if !capable {
                    continue;
                }
                if let Some(rx) = &arriving {
                    if rx.id == cancel.transfer_id {
                        rx.cancel();
                    }
                }
                if sending
                    .as_ref()
                    .is_some_and(|s| s.request.id == cancel.transfer_id)
                {
                    let mut active = sending.take().unwrap();
                    if active.total > 0 && active.sent == active.total {
                        // The receiver may already have published the last chunk. Let its final
                        // result settle the race; never turn that success into cancellation.
                        active.stop_producer();
                        active.cancel_sent = true;
                        active.waiting =
                            Some(tokio::time::Instant::now() + transfer::RESULT_TIMEOUT);
                        transfers.update(
                            owner,
                            &active.request.id,
                            active.sent,
                            "waiting confirmation",
                            "Receiver requested cancellation",
                        );
                        sending = Some(active);
                        continue;
                    }
                    transfers.update(
                        owner,
                        &active.request.id,
                        active.sent,
                        "cancelled",
                        "Cancelled by receiver",
                    );
                    active.request.finish(Err("Cancelled by receiver".into()));
                    let result = pb::FileResult {
                        transfer_id: active.request.id.clone(),
                        success: false,
                        cancelled: true,
                        error: "Cancelled by receiver".into(),
                        name: String::new(),
                    };
                    session
                        .send(&mut stream, pb::Kind::FileResult, &result.encode_to_vec())
                        .await?;
                    metrics.frames_out.fetch_add(1, Ordering::Relaxed);
                }
            }
            other => warn!(?other, "unhandled kind"),
        }
    }
}

fn now_ms() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_millis() as u64)
        .unwrap_or(0)
}

/// Writes the newest phone capture where the shell and Snipping Tool can both read it.
///
/// One file, overwritten each time, which is the same bound as the single capture toast
/// that names it. No transcode: the toast image loader and Snipping Tool each read JPEG
/// happily, the phone already downscaled it, and re-encoding a photograph as PNG would
/// multiply its size for nothing — local toast images are capped at 3 MB.
fn stage_capture(bytes: &[u8]) -> Result<PathBuf> {
    let (name, stale) = if bytes.starts_with(b"\x89PNG") {
        ("capture.png", "capture.jpg")
    } else {
        ("capture.jpg", "capture.png")
    };
    let dir = config_dir()?;
    // Switching between a JPEG camera photo and a PNG screenshot must not leave a second
    // staged capture behind. Best effort: the old toast/token is replaced in the same slot.
    let _ = std::fs::remove_file(dir.join(stale));
    let path = dir.join(name);
    std::fs::write(&path, bytes).with_context(|| format!("writing {}", path.display()))?;
    Ok(path)
}

/// 30 s idle / 10 s probe / 3 retries. Windows' `SIO_KEEPALIVE_VALS` has no retry
/// count, so socket2 only exposes `with_retries` elsewhere.
fn set_keepalive(stream: &TcpStream) -> Result<()> {
    let keepalive = socket2::TcpKeepalive::new()
        .with_time(Duration::from_secs(30))
        .with_interval(Duration::from_secs(10));
    #[cfg(not(windows))]
    let keepalive = keepalive.with_retries(3);
    socket2::SockRef::from(stream).set_tcp_keepalive(&keepalive)?;
    Ok(())
}

fn config_dir() -> Result<PathBuf> {
    data_dir::resolve()
}

#[cfg(test)]
mod heartbeat_tests {
    use super::*;

    #[test]
    fn only_a_pong_satisfies_an_outstanding_liveness_challenge() {
        let now = tokio::time::Instant::now();
        let mut heartbeat = Heartbeat::new(Duration::from_secs(240), Duration::from_secs(10));

        assert_eq!(heartbeat.deadline(Duration::from_secs(240), now), now);
        heartbeat.ping_sent(now);
        assert!(heartbeat.awaiting_pong());
        assert_eq!(
            heartbeat.deadline(Duration::ZERO, now + Duration::from_secs(5)),
            now + Duration::from_secs(10),
            "ordinary traffic must not move the absolute PONG deadline",
        );

        assert!(!heartbeat.observe(pb::Kind::ClipText));
        assert!(
            heartbeat.awaiting_pong(),
            "an ordinary frame incorrectly counted as PONG"
        );
        assert!(heartbeat.observe(pb::Kind::Pong));
        assert!(!heartbeat.awaiting_pong());
    }
}
